<p class="has-lg-font-size">This website, www.biblicalwisdomfordads.au, is run by Stephen Parker, author of <em>Biblical Wisdom for Dads</em>, and published by Running Forever Press, Brisbane, Australia. This policy explains what personal information the site collects, how it is used and who it is shared with. We handle personal information in line with the Australian Privacy Principles in the <em>Privacy Act 1988</em> (Cth).</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The short version: the site is a small book website. It does not have user accounts, comments, a newsletter or contact forms. We receive personal information only when you email us or buy the book through our Square checkout, and the site collects the ordinary technical information every website receives.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Information we collect</h2>
<!-- /wp:heading -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">When you email us</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>If you contact us at <a href="mailto:stephen@biblicalwisdomfordads.au">stephen@biblicalwisdomfordads.au</a>, we receive your email address, your name if you give it, and whatever you write. We use it to reply to you and to deal with your enquiry, such as a bulk order for a church or a request for retail or media information.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">When you buy the book directly</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Direct purchases, bulk orders and local pickup orders are taken through checkout pages hosted by Square (Block, Inc.) at square.link. When you place an order, Square collects your name, email address, delivery address, phone number if you provide it, and your payment card details. Your card details go to Square only. We never see or store them.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Square passes us your name, contact details, delivery address and order details so we can pack and post your order, confirm it with you and answer questions about it. Square handles your information under its own privacy policy, which you can read at <a href="https://squareup.com/au/en/legal/general/privacy" target="_blank" rel="noopener noreferrer">squareup.com/au/en/legal/general/privacy</a>.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Information collected automatically</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Like every website, this site records technical information about visits in server logs: your IP address, browser and device type, the pages you view, the site that referred you, and the date and time. If you use the site search, the words you search for appear in the page address and in those logs. This information is used to keep the site running, to protect it from abuse and to fix problems. It is not used to identify you personally.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>The site is served through Cloudflare, which sits between your browser and our web server. Cloudflare sees your IP address and request details in order to deliver pages, block malicious traffic and hide our email address from spam harvesters. Cloudflare may also receive anonymous network error reports from your browser. Cloudflare's privacy policy is at <a href="https://www.cloudflare.com/privacypolicy/" target="_blank" rel="noopener noreferrer">cloudflare.com/privacypolicy</a>.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Cookies and analytics</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The site itself does not set cookies for ordinary visitors. WordPress sets cookies only when someone logs in to administer the site. Cloudflare may set a short-lived security cookie if it needs to check that a visitor is not an automated bot.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>We use Google Analytics, through the Site Kit by Google plugin, to understand how many people visit the site and which pages they read. Google Analytics uses cookies and collects your IP address, device and browser details and the pages you visit. Google processes this information on our behalf and may store it on servers outside Australia. You can read how Google uses data from sites that use its services at <a href="https://policies.google.com/technologies/partner-sites" target="_blank" rel="noopener noreferrer">policies.google.com/technologies/partner-sites</a>, and opt out with the <a href="https://tools.google.com/dlpage/gaoptout" target="_blank" rel="noopener noreferrer">Google Analytics opt-out browser add-on</a>.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Facebook content on this site</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The home page shows a feed from our Facebook page using the Facebook Page Plugin. The feed is loaded directly from facebook.com, so when the home page loads, Meta Platforms receives your IP address and browser details and can set or read its own cookies, whether or not you have a Facebook account. If you are logged in to Facebook, Meta can link the visit to your account. We do not receive any of this information. Meta's privacy policy is at <a href="https://www.facebook.com/privacy/policy/" target="_blank" rel="noopener noreferrer">facebook.com/privacy/policy</a>. You can avoid the feed by not visiting the home page, or by using a browser setting or extension that blocks third-party content.</p>
<!-- /wp:paragraph -->

<!-- wp:heading -->
<h2 class="wp-block-heading">Links to other websites</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The site links to Amazon, where the paperback and eBook are sold, asks readers to review the book on Amazon and Goodreads, and links to our pages on Facebook, Instagram and LinkedIn. Those sites collect information under their own privacy policies once you leave ours. We do not control them and are not responsible for how they handle your information.</p>
