<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>The site is served over HTTPS, so information travelling between your browser and the site is encrypted. Payments are handled entirely by Square, which is certified to the Payment Card Industry Data Security Standard. Access to the site's administration and to order information is limited to the author and the people who maintain the site for him. No method of storage or transmission is completely secure, so we cannot guarantee absolute security, but we take reasonable steps to protect the information we hold.</p>
